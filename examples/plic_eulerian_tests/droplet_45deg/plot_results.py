#!/usr/bin/env python3
"""Plot helper for the 45-degree droplet PLIC benchmark.

Skeleton based on ``examples/droplet_advection_45deg/plot_results.py``
and ``run_vof_only.py`` (the in-memory plotting block). The plotting
routines accept plain numpy arrays and are therefore usable by either
the Stage 2 time loop (snapshots from memory) or a post-hoc pass over
``.npz`` files in ``results/``.

If no simulation output is available, ``main()`` draws a "mock"
initial-vs-analytic-final figure to verify the plot stack runs.
"""

from __future__ import annotations

import os
import sys
import glob

import numpy as np
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import LinearSegmentedColormap

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from case_config import CASE  # noqa: E402


# Academic VOF colormap, matching run_vof_only.py:195-197.
_CMAP = LinearSegmentedColormap.from_list(
    "vof", ["#FFFFFF", "#C6DBEF", "#6BAED6", "#2171B5", "#08306B"], N=256
)


def _interior_coords():
    nx = CASE["grid"]["nx"]
    ny = CASE["grid"]["ny"]
    x_range = CASE["domain"]["x"]
    y_range = CASE["domain"]["y"]
    dx = (x_range[1] - x_range[0]) / nx
    dy = (y_range[1] - y_range[0]) / ny
    x = np.linspace(x_range[0] + dx / 2.0, x_range[1] - dx / 2.0, nx)
    y = np.linspace(y_range[0] + dy / 2.0, y_range[1] - dy / 2.0, ny)
    return np.meshgrid(x, y, indexing="ij")


def plot_phase_evolution(snapshots, out_path: str) -> None:
    """Phase-evolution strip plot for a list of ``(t, F)`` pairs."""
    n = len(snapshots)
    if n == 0:
        return
    X, Y = _interior_coords()
    fig, axes = plt.subplots(1, n, figsize=(2.8 * n, 3.0), squeeze=False)
    axes = axes.ravel()
    R = CASE["droplet"]["radius"]
    cx0, cy0 = CASE["droplet"]["center"]
    for ax, (t, F) in zip(axes, snapshots):
        ax.contourf(X, Y, F, levels=np.linspace(0, 1, 21), cmap=_CMAP)
        ax.contour(X, Y, F, levels=[0.5], colors="k", linewidths=1.0)
        cx, cy = cx0 + t, cy0 + t  # exact 45-deg position
        theta = np.linspace(0, 2 * np.pi, 60)
        ax.plot(
            cx + R * np.cos(theta),
            cy + R * np.sin(theta),
            "g--", linewidth=1.0, alpha=0.7,
        )
        ax.set_xlim(*CASE["domain"]["x"])
        ax.set_ylim(*CASE["domain"]["y"])
        ax.set_aspect("equal")
        ax.set_title(f"t = {t:.3f} s", fontsize=10)
        ax.set_xlabel("x (m)", fontsize=9)
    axes[0].set_ylabel("y (m)", fontsize=9)
    fig.suptitle(
        "45-deg Droplet Advection - JAX-LaserAM PLIC research",
        fontsize=14, fontweight="bold",
    )
    plt.tight_layout()
    plt.savefig(out_path, dpi=200, bbox_inches="tight", facecolor="white")
    plt.close()
    print(f"Saved: {out_path}")


def plot_initial_vs_analytic(F_init: np.ndarray, out_path: str) -> None:
    """Mock plot drawn even without simulation output.

    Draws the initial tanh-smoothed droplet plus the analytic circle at
    the expected final position. Used as a smoke-test for the plotting
    stack before Stage 2 ships.
    """
    X, Y = _interior_coords()
    fig, ax = plt.subplots(1, 1, figsize=(6, 6))
    ax.contourf(X, Y, F_init, levels=np.linspace(0, 1, 21), cmap=_CMAP)
    ax.contour(X, Y, F_init, levels=[0.5], colors="blue", linewidths=2)

    cx_f, cy_f = CASE["analytic_final_center"]
    R = CASE["droplet"]["radius"]
    theta = np.linspace(0, 2 * np.pi, 120)
    ax.plot(
        cx_f + R * np.cos(theta),
        cy_f + R * np.sin(theta),
        "g--", linewidth=1.5, label="analytic final",
    )
    ax.set_xlim(*CASE["domain"]["x"])
    ax.set_ylim(*CASE["domain"]["y"])
    ax.set_aspect("equal")
    ax.legend(fontsize=10)
    ax.set_xlabel("x (m)", fontsize=12)
    ax.set_ylabel("y (m)", fontsize=12)
    ax.set_title("Initial droplet + analytic final position",
                 fontsize=13, fontweight="bold")
    ax.grid(True, alpha=0.3, ls="--")
    plt.tight_layout()
    plt.savefig(out_path, dpi=200, bbox_inches="tight", facecolor="white")
    plt.close()
    print(f"Saved: {out_path}")


def main() -> int:
    here = os.path.dirname(os.path.abspath(__file__))
    out_dir = os.path.join(here, "results")
    os.makedirs(out_dir, exist_ok=True)

    # --- Look for snapshots generated by Stage 2 ---
    snap_paths = sorted(glob.glob(os.path.join(out_dir, "snapshot_*.npz")))

    if snap_paths:
        snapshots = []
        for p in snap_paths:
            data = np.load(p)
            F = np.asarray(data["volume_fraction"])
            if F.ndim == 3:
                F = F[:, :, 0]
            snapshots.append((float(data["time"]), F))
        plot_phase_evolution(
            snapshots, os.path.join(out_dir, "phase_evolution.png")
        )
        return 0

    # --- Fallback: smoke-test plot with initial droplet only ---
    print(
        "No snapshots found in results/. Drawing initial-vs-analytic "
        "mock figure instead.",
        flush=True,
    )
    # Rebuild initial field via the init module (no JAX dep for plot).
    import jax

    jax.config.update("jax_enable_x64", True)
    from init_droplet import build_grid, create_droplet_vof  # noqa: E402

    grid = build_grid()
    F = np.asarray(create_droplet_vof(grid))
    ic_x = slice(grid.nh, grid.nh + grid.nx)
    ic_y = slice(grid.nh, grid.nh + grid.ny)
    # Pick the first interior z layer (quasi-2D: all layers identical)
    z_mid = grid.nh if grid.nz > 1 else 0
    F_interior = F[ic_x, ic_y, z_mid]
    plot_initial_vs_analytic(
        F_interior, os.path.join(out_dir, "initial_vs_analytic.png")
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
