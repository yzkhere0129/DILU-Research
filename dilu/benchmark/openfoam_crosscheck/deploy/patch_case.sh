#!/bin/bash
# patch_case.sh — attach matrix dumping to a pre-existing LPBF case.
#
# Assumes:
#   - The case has already run for a while; you want to RESUME from
#     the latest saved time and capture matrices for N more steps.
#   - `<case>/system/controlDict` and `<case>/system/fvSolution` exist.
#
# Usage:
#   ./patch_case.sh <case_dir> [N_STEPS_TO_DUMP]
#     N_STEPS_TO_DUMP: default 50 — number of additional steps to run
#                     from latestTime, dumping every step.
#
# What it does:
#   1. Drop `system/matrixDumperDict` into the case.
#   2. Back up current controlDict → controlDict.orig (if not already).
#   3. Edit controlDict:
#      - startFrom → latestTime
#      - endTime → latestTime + N_STEPS_TO_DUMP × maxDeltaT (conservative)
#      - writeInterval → adjust so fields written every ~10 steps
#   4. Print a ready-to-run command.

set -euo pipefail

CASE="${1:-}"
NSTEPS="${2:-50}"

if [ -z "$CASE" ] || [ ! -d "$CASE" ]; then
    echo "Usage: $0 <case_dir> [N_STEPS_TO_DUMP=50]"
    exit 1
fi

CASE="$(realpath "$CASE")"

if [ ! -f "$CASE/system/controlDict" ]; then
    echo "ERROR: $CASE/system/controlDict not found"
    exit 1
fi

# --- Detect latest time from directory listing (Not foamDictionary, to avoid
#     needing OpenFOAM env sourced on the prep machine) ---
LATEST_TIME=$(ls -1d "$CASE"/[0-9]* 2>/dev/null \
    | sed 's|.*/||' | sort -g | tail -1)
if [ -z "$LATEST_TIME" ]; then
    echo "WARNING: no time folder found — assuming this is a fresh case"
    LATEST_TIME=0
fi
echo "[patch_case] Latest time folder: $LATEST_TIME"

# --- Extract maxDeltaT if present; default 2e-8 ---
MAXDT=$(grep -E '^\s*maxDeltaT\s' "$CASE/system/controlDict" \
    | head -1 | awk '{print $2}' | tr -d ';')
MAXDT="${MAXDT:-2e-8}"
echo "[patch_case] maxDeltaT = $MAXDT (detected)"

# Conservative endTime:  latestTime + N_STEPS * maxDeltaT
END_TIME=$(awk -v t="$LATEST_TIME" -v n="$NSTEPS" -v dt="$MAXDT" \
    'BEGIN { printf "%.12g", t + n*dt }')
echo "[patch_case] new endTime = $END_TIME  (= $LATEST_TIME + $NSTEPS × $MAXDT)"

# --- Drop matrixDumperDict ---
cat > "$CASE/system/matrixDumperDict" <<EOF
/*--------------------------------*- C++ -*----------------------------------*\\
  matrixDumperDict — DILU-Research cross-check
  (auto-generated by patch_case.sh)
\\*---------------------------------------------------------------------------*/
FoamFile
{
    version     2.0;
    format      ascii;
    class       dictionary;
    location    "system";
    object      matrixDumperDict;
}

enabled        true;
binaryMM       false;
outputDir      "postProcessing/matrices";

// Run resumes from latestTime. Step index starts at 1 on the first
// ++runTime advance AFTER resume. So "dump every step" = list 1..$NSTEPS.
dumpTimeSteps  (\$(seq 1 $NSTEPS | tr '\\n' ' '));

equations      (pd T);

maxCorrectorsPerEq
{
    pd  3;
    T   2;
}

// ************************************************************************* //
EOF

# Replace the seq ... placeholder (bash inside heredoc requires eval)
# We regenerate via printf to be safe:
STEPS_LIST=$(seq 1 "$NSTEPS" | tr '\n' ' ')
sed -i "s|dumpTimeSteps.*|dumpTimeSteps  ($STEPS_LIST);|" "$CASE/system/matrixDumperDict"
echo "[patch_case] wrote system/matrixDumperDict (dump steps 1..$NSTEPS)"

# --- Patch controlDict ---
if [ ! -f "$CASE/system/controlDict.orig" ]; then
    cp "$CASE/system/controlDict" "$CASE/system/controlDict.orig"
    echo "[patch_case] backed up controlDict → controlDict.orig"
fi

# Rewrite endTime and ensure startFrom=latestTime
cp "$CASE/system/controlDict.orig" "$CASE/system/controlDict"
sed -i "s|^\(\s*startFrom\s\+\).*|\1latestTime;|" "$CASE/system/controlDict"
sed -i "s|^\(\s*endTime\s\+\).*|\1$END_TIME;|"    "$CASE/system/controlDict"

echo ""
echo "[patch_case] DONE."
echo ""
echo "Check / run:"
echo "  cd $CASE"
echo "  cat system/matrixDumperDict              # verify"
echo "  cat system/controlDict | grep -E 'Time'   # verify end/start"
echo "  laserMeltFoam | tee log.laserMeltFoam    # run (~ $NSTEPS steps)"
echo ""
echo "After the run, matrices will be in:"
echo "  $CASE/postProcessing/matrices/<time>/{pd_corr*,T_corr*}/"
echo ""
echo "To restore original controlDict after the run:"
echo "  mv system/controlDict.orig system/controlDict"
